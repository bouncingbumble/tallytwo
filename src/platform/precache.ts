/**
 * What the service worker saves for offline play, decided from the built dist/ file list. PURE (no
 * DOM, no node:): vite.config.ts's `tally-offline` plugin walks dist/, hands the files here and
 * inlines the result into dist/sw.js; precache.test.ts pins the rules. docs/OFFLINE_PLAN.md.
 *
 * - **core** must all be cached for the worker to install: the page, the JS and CSS, the woff2
 *   font, every image, the SFX, the icons and the web manifest.
 * - **music** (the ost_* loops, ~11 MB) is cached best-effort, one file at a time, so a flaky
 *   first visit still installs; a file that missed is filled in when the game first fetches it.
 * - **skipped**: sw.js itself (never precache the worker), the .woff twins of the woff2 fonts
 *   (every target reads woff2), the dev /assets page's chunks, source maps.
 */

export interface DistFile {
  /** Path relative to dist/, forward slashes: "assets/index-Cj2GbNVG.js", "index.html". */
  path: string;
  /** A content hash of the file (any stable string); folded into the version. */
  hash: string;
  size: number;
}

export interface OfflinePlan {
  /** Changes whenever any precached file's content or path changes: names the caches. */
  version: string;
  /** Absolute URL paths (base-prefixed), sorted. */
  core: string[];
  music: string[];
  /** Total bytes of core + music. */
  bytes: number;
}

export type FileClass = "core" | "music" | "skip";

const MUSIC_RE = /(^|\/)ost_[^/]*\.m4a$/;
const CORE_RE = /\.(html|js|css|woff2|png|m4a|webmanifest|json)$/;

export function classify(path: string): FileClass {
  if (path === "sw.js") return "skip";
  if (/(^|\/)assetsPage-[^/]*$/.test(path)) return "skip";
  if (MUSIC_RE.test(path)) return "music";
  if (CORE_RE.test(path)) return "core";
  return "skip";
}

/** FNV-1a, 32 bit, over a string; hex. Enough to tell builds apart; not a security hash. */
export function fnv1a(s: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(16).padStart(8, "0");
}

/** The same hash over bytes (the plugin hashes each file's contents with it). */
export function fnv1aBytes(b: Uint8Array): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < b.length; i++) {
    h ^= b[i];
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(16).padStart(8, "0");
}

/** `base` is Vite's public path ("/" or "/tallytwo/"). */
export function precachePlan(files: readonly DistFile[], base: string): OfflinePlan {
  const root = base.endsWith("/") ? base : base + "/";
  const kept = files
    .map((f) => ({ ...f, path: f.path.replace(/\\/g, "/").replace(/^\/+/, "") }))
    .filter((f) => classify(f.path) !== "skip")
    .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const core: string[] = [];
  const music: string[] = [];
  let bytes = 0;
  for (const f of kept) {
    (classify(f.path) === "music" ? music : core).push(root + f.path);
    bytes += f.size;
  }
  const version = fnv1a(root + "\n" + kept.map((f) => `${f.path} ${f.hash}`).join("\n"));
  return { version, core, music, bytes };
}

/**
 * The worker script: the plan as a `PLAN` constant, then the worker body (src/platform/sw.js,
 * plain JS that reads PLAN). The page's index is served for navigations, so it must be core.
 */
export function renderWorker(plan: OfflinePlan, base: string, body: string): string {
  const root = base.endsWith("/") ? base : base + "/";
  const index = root + "index.html";
  if (!plan.core.includes(index)) throw new Error(`offline: ${index} is not in the precache`);
  const header = `// Generated by vite.config.ts (tally-offline) from src/platform/sw.js. Do not edit.\n`;
  const data = { version: plan.version, base: root, index, core: plan.core, music: plan.music };
  return `${header}const PLAN = ${JSON.stringify(data, null, 1)};\n\n${body}`;
}
